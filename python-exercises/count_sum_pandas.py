#   Задание: Необходимо посчитать сумму по продуктам
#   Пример входного значения:

#   Дата	    Товар	Количество
#   07.05.2022	Банан	30
#   07.05.2022	Хлеб	10
#   08.05.2022	Банан	40
#   08.05.2022	Хлеб	8

#   Пример выходного значения:

#   Товар	Количество
#   Банан	70
#   Хлеб	18

#   Требования к скрипту:

#   1) Название скрипта count_sum_pandas.py
#   2) Название функции count_sum
#   3) На вход функции подается элемент типа DataFrame
#   4) Функция возвращает элемент типа DataFrame
#   5) Поле Товар является индексом в ответе

import pandas as pd


def count_sum(df: pd.DataFrame) -> pd.DataFrame:
    return df.groupby('Товар')[['Количество']].sum()

data = {
        'Дата': ['07.05.2022', '07.05.2022', '08.05.2022', '08.05.2022'],
        'Товар': ['Банан', 'Хлеб', 'Банан', 'Хлеб'],
        'Количество': [30, 10, 40, 8],
}

df = pd.DataFrame(data)
print(df)
print(count_sum(df))